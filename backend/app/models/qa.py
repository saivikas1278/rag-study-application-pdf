"""Domain schemas for question answering and LLM generation."""

from typing import List
from pydantic import BaseModel, Field, field_validator


class Citation(BaseModel):
    """Citation referencing a specific source PDF document and 1-based page number."""
    filename: str = Field(..., description="Sanitized source PDF filename")
    page_number: int = Field(..., description="1-based page number where evidence appears")


class GroundedAnswer(BaseModel):
    """Structured response containing a grounded answer and associated source citations."""
    answer: str = Field(..., description="Grounded answer text generated by the model")
    citations: List[Citation] = Field(
        default_factory=list,
        description="List of source citations supporting the answer"
    )
    model_used: str = Field(..., description="Gemini model identifier used for generation")
    has_sufficient_context: bool = Field(
        ...,
        description="Whether the provided document context contained sufficient evidence to answer the question"
    )


class QueryRequest(BaseModel):
    """Request schema for RAG question-answering query."""
    question: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="The student question to answer using indexed study documents."
    )
    top_k: int = Field(
        default=6,
        ge=1,
        le=20,
        description="Maximum number of relevant document chunks to retrieve as context (between 1 and 20)."
    )

    @field_validator("question")
    @classmethod
    def validate_question_not_whitespace(cls, value: str) -> str:
        """Ensures the question contains non-whitespace content."""
        trimmed = value.strip()
        if not trimmed:
            raise ValueError("question cannot be empty or whitespace only.")
        return trimmed


class QueryResponse(BaseModel):
    """Structured response schema returned by the /api/query endpoint."""
    question: str = Field(..., description="The student question that was queried")
    answer: str = Field(..., description="Grounded answer text generated from document evidence")
    citations: List[Citation] = Field(
        default_factory=list,
        description="List of source citations supporting the answer"
    )
    has_sufficient_context: bool = Field(
        ...,
        description="Whether the retrieved documents contained sufficient evidence to answer"
    )
    model_used: str = Field(..., description="Gemini model identifier used for generation")

